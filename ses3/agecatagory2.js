const age = 20;
if (age >=0 && age <=5 ) {
    console.log("toddler")
}else if (age >= 6 && age <=12) {
    console.log("child")
}else if (age >=13 && age <=17) {
    console.log("teenager")
}else if (age >= 18 && age <= 59) {
    console.log("adult")
}else if (age >= 60) {
    console.log("senior")
}